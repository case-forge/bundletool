// ── Wrapping ─────────────────────────────────────────────────────────────────

test('wrapping breaks on words and keeps every one of them', async () => {
  const doc = await PDFDocument.create();
  doc.registerFontkit(await getFontkit());
  const font = await doc.embedFont(
    await fetch(getFontSettings('serif').regular.url).then((r) => r.arrayBuffer()),
  );
  const value = 'MS ALEXANDRA BEATRICE CHARLOTTE DELACROIX-WINTERBOTTOM (formerly known as MS A B C DELACROIX)';
  const lines = wrapText(value, font, 10, PAGE_WIDTH - 2 * MARGIN);
  assert.ok(lines.length > 1, 'a name this long must wrap');
  assert.equal(lines.join(' '), value, 'wrapping must not lose or reorder a word');
  for (const line of lines) {
    assert.ok(font.widthOfTextAtSize(line, 10) <= PAGE_WIDTH - 2 * MARGIN,
      `line overflows the text column: ${line}`);
  }
  assert.deepEqual(wrapText('', font, 10, 400), []);
  assert.deepEqual(wrapText(null, font, 10, 400), []);
});

