test('every field the cover is given reaches the page', async (t) => {
  if (!havePdftotext()) return skip('pdftotext is needed to read the rendered page');
  const text = coverText(await makeCoverPdf(FULL));

  for (const expected of [
    'IN THE FAMILY COURT AT CENTRAL LONDON',
    'IN THE MATTER OF THE FAMILY LAW ACT 1996',
    'CASE NO: ZC00P00456',
    'MS A SAMPLE',
    'APPLICANT',
    'MR B EXAMPLE',
    'RESPONDENT',
    'BUNDLE FOR HEARING ON 14 MARCH 2026',
    'Prepared by: Example Solicitors',
  ]) {
    assert.ok(text.includes(expected), `the cover does not carry ${JSON.stringify(expected)}: ${text}`);
  }
  // heading.projectName ("Parties") is collected for the PDF's Subject
  // metadata (bundletoolMeta.js) but is not drawn on the page itself: the
  // middle band already names the parties.
  assert.ok(!text.includes('Re: X (A Child)'),
    'the case name is redundant with Applicant/Respondent and must not be drawn twice');

  // ...and in that order: court, case number, matter-of, then the parties,
  // top to bottom; the title and "Prepared by" are pinned to the foot of
  // the page (see GEOMETRY in bundletoolCover.js), so they read LAST on a
  // page this short, same as pdftotext's own top-to-bottom order.
  // pdftotext groups by physical row, not by column: the two names share a
  // row (left then right), then the two labels share the next row (left
  // then right), not name-then-its-own-label the way reading a single
  // column would.
  const order = ['IN THE FAMILY COURT', 'CASE NO', 'IN THE MATTER OF',
    'MS A SAMPLE', 'MR B EXAMPLE', 'APPLICANT', 'RESPONDENT',
    'BUNDLE FOR HEARING ON', 'Prepared by:'];
  let at = -1;
  for (const token of order) {
    const next = text.indexOf(token, at + 1);
    assert.ok(next > at, `${token} is out of order on the cover: ${text}`);
    at = next;
  }
});

