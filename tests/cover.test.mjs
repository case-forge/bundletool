/**
 * The generated cover page.
 *
 * Two layouts, `cover.layout`: see the TWO LAYOUTS comment in
 * bundletoolCover.js. The tests before the "── Classic layout ──" section run
 * against the FULL fixture, which is pinned to 'grid' explicitly; that section
 * mirrors them against 'classic', the default. Most of what matters in either
 * is "is the right thing on the page, in the right order, on one page" rather
 * than exact coordinates.
 *
 * Rendering the page to text needs pdftotext; those tests skip without it. The
 * ones that do not need it check the layout arithmetic directly, so the module
 * is never completely unexercised.
 *
 * Every fixture here is invented. No client material.
 */
