test('the gap scaling is what keeps a crowded cover on the page', async () => {
  // The measurement without the drawing: layoutCover() reports where the last
  // flowed line landed. At full gaps the crowded case runs below the floor;
  // makeCoverPdf() is what tries smaller gaps, so prove both halves.
  const doc = await PDFDocument.create();
  doc.registerFontkit(await getFontkit());
  const settings = getFontSettings('serif');
  const fonts = {
    regular: await doc.embedFont(await fetch(settings.regular.url).then((r) => r.arrayBuffer())),
    bold: await doc.embedFont(await fetch(settings.bold.url).then((r) => r.arrayBuffer())),
  };
  // This fixture is deliberately absurd. Ordinary input (even the very long
  // party names in the test above) clears the floor at full gaps with room to
  // spare, which is the intended behaviour: the CLI's spacing is used exactly
  // unless it genuinely cannot be. Reaching the scaling at all takes a single
  // "name" absurd enough to wrap into two dozen-plus lines within its own
  // half-width column, so the fixture is built to have that rather than
  // dressed up as a realistic case it is not.
  const many = (word, n) => Array(n).fill(word).join(' ');
  const crowded = {
    ...FULL,
    'cover.applicantName': many('APPLICANT', 120),
    'cover.respondentName': many('RESPONDENT', 120),
  };
  const atFullGaps = layoutCover(crowded, fonts, 1, null);
  assert.ok(atFullGaps < CONTENT_FLOOR,
    `this fixture is meant to overflow at full gaps but reached ${atFullGaps.toFixed(1)}; `
    + 'so it does not test the scaling');
  assert.ok(layoutCover(crowded, fonts, 0.3, null) > atFullGaps,
    'shrinking the gaps must actually recover vertical space');

  const rendered = await PDFDocument.load(await makeCoverPdf(crowded));
  assert.equal(rendered.getPageCount(), 1);

  // A modest cover must NOT be squeezed: the scaling only fires when needed.
  assert.ok(layoutCover(FULL, fonts, 1, null) >= CONTENT_FLOOR,
    'an ordinary cover should fit at full gaps and keep the CLI spacing exactly');
});

test('"Prepared by" sits clear of the page-number footer zone', () => {
  // The footer plate starts 8pt up and is at most ~47pt tall at the largest
  // footer size, with 4pt of blanking above it. If this line moved down into
  // that band the blanking rectangle would erase it on every bundle.
  assert.ok(PREPARED_BY_Y > 8 + 47 + 4,
    `PREPARED_BY_Y ${PREPARED_BY_Y} is inside the footer's blanking zone`);
  assert.ok(CONTENT_FLOOR > PREPARED_BY_Y,
    'flowed content must stop above the "Prepared by" line, not on top of it');
});

