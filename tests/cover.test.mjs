// ── Court Ref/Claim No., Bundle Title and Prepared By follow Basic Information until the
// coversheet overrides them ────────────────────────────────────────────────────────

test('the cover follows Basic Information when it has no title of its own', () => {
  const cv = { 'heading.bundleTitle': 'Basic Info Title', 'cover.bundleTitle': null };
  assert.equal(coverTitle(cv), 'BASIC INFO TITLE');
  assert.equal(coverTitle({ 'heading.bundleTitle': 'Basic Info Title' }), 'BASIC INFO TITLE', 'undefined follows too');
});

test('a title set on the coversheet wins over Basic Information, and changing Basic Information later does not move it', () => {
  const cv = { 'heading.bundleTitle': 'Basic Info Title', 'cover.bundleTitle': 'Cover Only Title' };
  assert.equal(coverTitle(cv), 'COVER ONLY TITLE');
  assert.equal(coverTitle({ ...cv, 'heading.bundleTitle': 'Changed In Step 1' }), 'COVER ONLY TITLE');
});

test('an empty cover title is a deliberate override, not "follow"', () => {
  // The cover can leave a line out that Basic Information fills; an empty title falls to
  // the bare word, the same as a blank Basic Information title does.
  assert.equal(coverTitle({ 'heading.bundleTitle': 'Filled In', 'cover.bundleTitle': '' }), 'BUNDLE');
});

test('Court Ref/Claim No. and Prepared By follow Basic Information, or are overridden on the cover', async (t) => {
  if (!havePdftotext()) return skip('pdftotext is needed to read the rendered page');
  const base = { ...FULL, 'heading.claimNumber': 'BASIC-REF-1', 'heading.author': 'Basic Author' };
  const follows = coverText(await makeCoverPdf({ ...base, 'cover.claimNumber': null, 'cover.author': null }));
  assert.ok(follows.includes('BASIC-REF-1') && follows.includes('Basic Author'), `should follow: ${follows}`);
  const own = coverText(await makeCoverPdf({ ...base, 'cover.claimNumber': 'COVER-REF-9', 'cover.author': 'Cover Author' }));
  assert.ok(own.includes('COVER-REF-9') && own.includes('Cover Author'), `should use its own: ${own}`);
  assert.ok(!own.includes('BASIC-REF-1') && !own.includes('Basic Author'), 'Basic Information values must not leak through an override');
  const blank = coverText(await makeCoverPdf({ ...base, 'cover.author': '' }));
  assert.ok(!blank.includes('Prepared by'), 'an empty override leaves the Prepared by line off');
});
